export function seedRows(): SeedRow[] {
  const rows: SeedRow[] = [];
  const push = (collection: string, items: { slug: string; data: unknown }[]) => {
    items.forEach((item, index) => {
      rows.push({ collection, slug: item.slug, data: item.data, position: index });
    });
  };

  push("products", products.map((p) => ({ slug: p.slug, data: p })));
  push("categories", categories.map((c) => ({ slug: c.slug, data: c })));
  push("brands", brands.map((b) => ({ slug: b.slug, data: b })));
  push("industries", industries.map((i) => ({ slug: i.slug, data: i })));
  push("services", services.map((s) => ({ slug: s.slug, data: s })));
  push("articles", articles.map((a) => ({ slug: a.slug, data: a })));
  push("projects", projects.map((p) => ({ slug: p.slug, data: p })));
  push("parts", spareParts.map((p) => ({ slug: p.partNo, data: p })));
  push("offices", offices.map((o) => ({ slug: slugifyCity(o.city), data: o })));
  push("pages", pages.map((p) => ({ slug: p.slug, data: p })));

  return rows;
}

/** شناسه دفتر از نام شهر ساخته می‌شود؛ فارسی در URL مشکلی ندارد ولی فاصله دارد. */
function slugifyCity(city: string): string {
  return city.trim().replace(/\s+/g, "-");
}
